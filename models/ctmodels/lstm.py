# Vendored from ncps/ncps/torch/lstm.py; sequence wrapper added below.
import torch
from torch import nn

from ._sequence import SequenceModel, positive_int


class LSTMCell(nn.Module):
    def __init__(self, input_size, hidden_size):
        super(LSTMCell, self).__init__()
        self.input_size = input_size
        self.hidden_size = hidden_size
        self.input_map = nn.Linear(input_size, 4 * hidden_size, bias=True)
        self.recurrent_map = nn.Linear(hidden_size, 4 * hidden_size, bias=False)
        self.tanh = nn.Tanh()
        self.sigmoid = nn.Sigmoid()
        self.init_weights()

    def init_weights(self):
        for w in self.input_map.parameters():
            if w.dim() == 1:
                torch.nn.init.uniform_(w, -0.1, 0.1)
            else:
                torch.nn.init.xavier_uniform_(w)
        for w in self.recurrent_map.parameters():
            if w.dim() == 1:
                torch.nn.init.uniform_(w, -0.1, 0.1)
            else:
                torch.nn.init.orthogonal_(w)

    def forward(self, inputs, states):
        output_state, cell_state = states
        z = self.input_map(inputs) + self.recurrent_map(output_state)
        i, ig, fg, og = z.chunk(4, 1)

        input_activation = self.tanh(i)
        input_gate = self.sigmoid(ig)
        forget_gate = self.sigmoid(fg + 1.0)
        output_gate = self.sigmoid(og)

        new_cell = cell_state * forget_gate + input_activation * input_gate
        output_state = self.tanh(new_cell) * output_gate

        return output_state, new_cell


class LSTM(SequenceModel):
    """ncps LSTM cell with a sequence adapter; forget-gate bias is +1.

    timespans are accepted for interface compatibility but do not affect
    this discrete-time baseline. State is always a tuple (h, c).
    """

    def __init__(self, input_size, hidden_size, output_size=None, *,
                 batch_first=True, return_sequences=True):
        positive_int("input_size", input_size)
        positive_int("hidden_size", hidden_size)
        super().__init__(
            input_size, hidden_size, LSTMCell(input_size, hidden_size),
            output_size=output_size, batch_first=batch_first,
            return_sequences=return_sequences, lstm=True,
        )
